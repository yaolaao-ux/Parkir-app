CREATE TABLE vehicle_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_name VARCHAR(50) NOT NULL UNIQUE,
    first_hour_rate NUMERIC(12, 2) NOT NULL CHECK (first_hour_rate >= 0),
    hourly_rate NUMERIC(12, 2) NOT NULL CHECK (hourly_rate >= 0),
    grace_period_minutes INTEGER NOT NULL DEFAULT 5 CHECK (grace_period_minutes >= 0),
    lost_ticket_fee NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (lost_ticket_fee >= 0),
    max_daily_rate NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (max_daily_rate >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rfid_uid VARCHAR(100) NOT NULL UNIQUE,
    full_name VARCHAR(100) NOT NULL,
    license_plate VARCHAR(20) NOT NULL,
    vehicle_type_id BIGINT REFERENCES vehicle_types(id),
    expired_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'EXPIRED', 'SUSPENDED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN', 'CASHIER')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    action VARCHAR(50) NOT NULL,
    entity_type VARCHAR(50) NOT NULL,
    entity_id VARCHAR(100),
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    source_ip INET,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_audit_logs_created_at ON audit_logs (created_at DESC);
CREATE INDEX ix_audit_logs_actor_action ON audit_logs (actor_user_id, action, created_at DESC);

CREATE TABLE devices (
    device_id VARCHAR(50) PRIMARY KEY,
    device_type VARCHAR(30) NOT NULL CHECK (device_type IN ('GATE_IN', 'CASHIER_POS')),
    display_name VARCHAR(100) NOT NULL,
    firmware_version VARCHAR(50),
    ip_address INET,
    last_seen TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_devices_last_seen ON devices (last_seen DESC);

CREATE TABLE gates (
    gate_id VARCHAR(20) PRIMARY KEY,
    gate_type VARCHAR(20) NOT NULL CHECK (gate_type IN ('GATE_IN', 'GATE_OUT')),
    display_name VARCHAR(100) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

